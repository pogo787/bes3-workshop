// Generates docs/write-lab-tier-list.md from the generated address registry and
// the production write policy. No hardware, network or third-party packages.
//
//   node tools/build-write-lab-tier-list.mjs
//
// The generated document is committed so the full tier list can be reviewed
// without running the code; run this script again when the registry changes.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.join(here, '..');
const POLICY = require(path.join(repo, 'web', 'workshop', 'write-policy.js'));
const REGISTRY = require(path.join(repo, 'src', 'address-registry.generated.js')).ADDRESS_REGISTRY.addresses;

const ORDER = ['blocked', 'registry-readonly', 'high-impact', 'normal'];
const rows = REGISTRY.map((e) => {
  const tier = POLICY.genericTier(e.component, e.name);
  return {
    component: e.component,
    name: e.name,
    address: '0x' + e.address.toString(16),
    label: e.label,
    kind: e.kind || 'unknown',
    writable: e.writable === true,
    readable: e.readable !== false,
    tier: tier.tier,
    reason: tier.reason || '',
  };
});

const counts = {};
for (const t of ORDER) counts[t] = rows.filter((r) => r.tier === t).length;
const writable = rows.filter((r) => r.writable).length;
const readable = rows.filter((r) => r.readable).length;
const unreadable = rows.length - readable;
const unreadableWritable = rows.filter((r) => !r.readable && r.writable).length;
const unreadableReadonly = unreadable - unreadableWritable;
const esc = (s) => String(s).replace(/\|/g, '\\|');

const descriptions = {
  blocked: 'Not offered for writing. The policy reserves the register for a dedicated control, or it is not in the registry.',
  'registry-readonly': 'The registry marks these read-only. They are offered under the same typed `Component.NAME` confirmation as high-impact; the bike will usually refuse the write.',
  'high-impact': 'Writable, but requires typing the full `Component.NAME` and a `highImpactConfirmed` approval grant.',
  normal: 'Writable without the extra high-impact name confirmation. Every write is still individually approved.',
};

let md = `# Write Lab tier list

Generated from \`src/address-registry.generated.js\` by \`tools/build-write-lab-tier-list.mjs\`.
Do not edit this file by hand. It is a snapshot of every registry entry and the
tier the Write Lab assigns to it.

- Registry entries: **${rows.length}**
- Writable: **${writable}**
- Read-only: **${rows.length - writable}**
- Readable: **${readable}**
- Not readable (cannot be read back): **${unreadable}** (${unreadableWritable} writable, ${unreadableReadonly} read-only)
- Tiers: **${counts.blocked} blocked**, **${counts['registry-readonly']} registry-readonly**,
  **${counts['high-impact']} high-impact**, **${counts.normal} normal**

Tier precedence: \`blocked\` (not in the registry, or \`DriveUnit.BIKE_LIGHT_POWER\`,
which has its own control) → \`registry-readonly\` (\`writable !== true\`) →
\`high-impact\` (the high-impact pair list or a sensitive name pattern) →
\`normal\`.

The writer boundary re-checks every tier. A registry read-only entry and a
high-impact entry both require the typed \`Component.NAME\` confirmation, carried
as \`highImpactConfirmed: true\` on the approval grant; the bike will usually
refuse a read-only write. A write-only entry cannot be read back, so a
transmitted write is reported as \`unverified (cannot be read back)\` and
\`applied\` stays false. Nothing is retried or rolled back.
`;

for (const tier of ORDER) {
  const group = rows.filter((r) => r.tier === tier)
    .sort((a, b) => (a.component + '.' + a.name).localeCompare(b.component + '.' + b.name));
  md += `\n## ${tier} (${group.length})\n\n${descriptions[tier]}\n\n`;
  md += '| Component | Register | Address | Kind | Writable | Readable | Label | Reason |\n';
  md += '| --- | --- | --- | --- | --- | --- | --- | --- |\n';
  for (const r of group) {
    md += `| ${esc(r.component)} | ${esc(r.name)} | ${esc(r.address)} | ${esc(r.kind)} | ${r.writable ? 'yes' : 'no'} | ${r.readable ? 'yes' : 'no'} | ${esc(r.label)} | ${esc(r.reason)} |\n`;
  }
}

const out = path.join(repo, 'docs', 'write-lab-tier-list.md');
fs.writeFileSync(out, md, 'utf8');
console.log('wrote ' + path.relative(repo, out) + ':', rows.length, 'entries', JSON.stringify(counts));
